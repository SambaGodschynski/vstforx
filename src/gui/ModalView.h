//============================================================================================================
// Klasse ModalView:
//============================================================================================================
class ModalView : 
	public CViewContainer,
	public EventListener<OnResize>
{
public:
	//-------------------------------------------------------------------------------------------------------
	ModalView ( const VSTGUI::CRect &size, CFrame *frame );
	//-------------------------------------------------------------------------------------------------------
	virtual void addWindowView( WindowView *view );
	//-------------------------------------------------------------------------------------------------------
	virtual void removeWindowView( WindowView *view );
	//-------------------------------------------------------------------------------------------------------
	void show() {
		pParentFrame->setModalView ( this );
		pParentFrame->setDirty();
	}
	//-------------------------------------------------------------------------------------------------------
	void hide() {
		pParentFrame->removeView ( this, false );
		pParentFrame->setModalView ( NULL );
		pParentFrame->setDirty();
	}
	//-------------------------------------------------------------------------------------------------------
	void eventHandler ( void *src, const OnResize &ev );
};
