//============================================================================================================
// Klasse ListBox:
//============================================================================================================
class ListBox : public MyScrollView {
public:
	//--------------------------------------------------------------------------------------------------------
	typedef list<ListBoxContent::Ptr> ContentCollection;
private:
	//::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
	class ListBoxView : public CView {
	private:
		//----------------------------------------------------------------------------------------------------
		int selection;
		//----------------------------------------------------------------------------------------------------
		ContentCollection cntCol;
	protected:
		//----------------------------------------------------------------------------------------------------
		virtual void findSelection ( const CPoint &p );
	public:
		//----------------------------------------------------------------------------------------------------
		ListBoxView ( const VSTGUI::CRect &rect );
		//----------------------------------------------------------------------------------------------------
		virtual ~ListBoxView(); 
		//----------------------------------------------------------------------------------------------------
		virtual void mouse ( CDrawContext *cD, CPoint &p, long btn=-1 );
		//----------------------------------------------------------------------------------------------------
		virtual void draw ( CDrawContext *cD );
		//----------------------------------------------------------------------------------------------------
		virtual size_t getNumEntries() { return cntCol.size(); }
		//----------------------------------------------------------------------------------------------------
		virtual ListBoxContent::Ptr getListBoxContent ( size_t index ) const;
		//----------------------------------------------------------------------------------------------------
		virtual const ContentCollection & getContentCollection() { return cntCol; }
		//----------------------------------------------------------------------------------------------------
		virtual void setContentCollection( const ContentCollection &c ) { cntCol = c; }
		//----------------------------------------------------------------------------------------------------
		virtual void clear();
		//----------------------------------------------------------------------------------------------------
		virtual void addListBoxContent ( const ListBoxContent::Ptr &ptr );
		//----------------------------------------------------------------------------------------------------
		VSTGUI::CRect calcSize();
		//----------------------------------------------------------------------------------------------------
		virtual void changeEntry ( size_t index, const ListBoxContent::Ptr &ptr );
		//----------------------------------------------------------------------------------------------------
		virtual void removeEntry ( size_t index );
		//----------------------------------------------------------------------------------------------------
		// -1 == nichts ausgewaehlt
		virtual int getSelectedIndex() const { return selection; }

	} *lBView;
	//::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::::
protected:
public:
	//--------------------------------------------------------------------------------------------------------
	void scrollToVEnd();
	//--------------------------------------------------------------------------------------------------------
	virtual void addString ( const string &str );
	//--------------------------------------------------------------------------------------------------------
	virtual string getString ( size_t index ) const;
	//--------------------------------------------------------------------------------------------------------
	virtual void removeEntry ( size_t index ) { 
		lBView->removeEntry(index); 
		setContainerSize ( lBView->calcSize() );
	}
	//--------------------------------------------------------------------------------------------------------
	virtual void clear() { lBView->clear(); }
	//--------------------------------------------------------------------------------------------------------
	// liefert -1 wenn nicht gefunden.
	virtual int find( const string &str );
	//--------------------------------------------------------------------------------------------------------
	virtual void changeEntry ( size_t index, const string &str );
	//--------------------------------------------------------------------------------------------------------
	// -1 == nichts ausgewaehlt
	virtual int getSelectedIndex() const { return lBView->getSelectedIndex(); }
	//--------------------------------------------------------------------------------------------------------
	virtual void drawBackgroundRect (CDrawContext *pContext, VSTGUI::CRect &_updateRect);
	//--------------------------------------------------------------------------------------------------------
	ListBox ( const VSTGUI::CRect &rect, CFrame *parent );
	//--------------------------------------------------------------------------------------------------------
	virtual size_t getNumEntries() { return lBView->getNumEntries(); }
	//--------------------------------------------------------------------------------------------------------
	virtual ~ListBox();
	//----------------------------------------------------------------------------------------------------
	virtual const ContentCollection & getContentCollection() { return lBView->getContentCollection(); }
	//----------------------------------------------------------------------------------------------------
	virtual void setContentCollection( const ContentCollection &c ) { lBView->setContentCollection(c); }
};
