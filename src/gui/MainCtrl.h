namespace ppiGui {
//============================================================================================================
// Klasse MainCtrl:
//============================================================================================================
class MainCtrl : 
	public CFrame, 
	public EventSender<OnResize>,
	public EventListener<ToolBoxBtnPressed>,
	public EventListener<OnClose>
{
private:
	//--------------------------------------------------------------------------------------------------------
	MToolBox *toolBx;
	//--------------------------------------------------------------------------------------------------------
	SetupCtrl *setupCtrl;
protected:
public:
	//--------------------------------------------------------------------------------------------------------
	typedef boost::shared_ptr<MainCtrl> Ptr;
	//--------------------------------------------------------------------------------------------------------
	virtual bool setSize (CCoord width, CCoord height);
	//--------------------------------------------------------------------------------------------------------
	MainCtrl( VSTGUI::CRect &size, void *pSystemWindow, void *pEditor );  
	//--------------------------------------------------------------------------------------------------------
	virtual ~MainCtrl();
	//--------------------------------------------------------------------------------------------------------
	SetupCtrl * getSetupCtrl() { return setupCtrl; }
	//--------------------------------------------------------------------------------------------------------
	virtual void update ( CDrawContext *cc );
	//--------------------------------------------------------------------------------------------------------
	void eventHandler ( void *src, const ToolBoxBtnPressed &ev );
	//--------------------------------------------------------------------------------------------------------
	void eventHandler ( void *src, const OnClose &ev );
	//--------------------------------------------------------------------------------------------------------
	MToolBox * getToolBox () { return toolBx; }
};
//============================================================================================================
// Klasse ButtonGroupListener:
// Es kann nur ein knopf gedreuckt werden.
//============================================================================================================
class ButtonGroupListener : public CControlListener, public EventSender<ToolBoxBtnPressed> {
private:
	//--------------------------------------------------------------------------------------------------------
	typedef list<CControl*> Views;
	//--------------------------------------------------------------------------------------------------------
	Views views;
	//--------------------------------------------------------------------------------------------------------
	CFrame *frame;
protected:
public:
	//--------------------------------------------------------------------------------------------------------
	void addControl ( CControl *ctrl ) {
		views.push_back ( ctrl );
	}
	//--------------------------------------------------------------------------------------------------------
	virtual void valueChanged ( CDrawContext *cD, CControl *pControl );
};
//============================================================================================================
// Klasse MToolBox:
// MainToolBox enthaelt Buttons die die CircuidControl Steuern.
//============================================================================================================
class MToolBox : 
	public CView, 
	private CControlListener, 
	public EventSender<ToolBoxBtnPressed>, 
	public EventListener<ToolBoxBtnPressed>,
	public EventListener<OnResize>
{
private:
	//--------------------------------------------------------------------------------------------------------
	CView **views;
	//--------------------------------------------------------------------------------------------------------
	CFrame *frame;
	//--------------------------------------------------------------------------------------------------------
	typedef vector<ButtonGroupListener> Groups;
	//--------------------------------------------------------------------------------------------------------
	Groups groups;
	//--------------------------------------------------------------------------------------------------------
	void initGroups();
protected:
	//--------------------------------------------------------------------------------------------------------
	CCoord lastXPos; // X pos des letzten eingefuegten elementes
public:
	//--------------------------------------------------------------------------------------------------------
	void eventHandler ( void *src, const ToolBoxBtnPressed &ev ) {
		EventSender<ToolBoxBtnPressed>::notifyEventListeners ( this, ev );
	}
	//--------------------------------------------------------------------------------------------------------
	enum ToolBoxEl { tBtnUse, 
				     tBtnConnect,
					 tBtnMove,
					 tBtnSetup,
					 tNum }; 
	//--------------------------------------------------------------------------------------------------------
	CView * getObject ( ToolBoxEl el ) { return views[el]; }
	//--------------------------------------------------------------------------------------------------------
	virtual void eventHandler(void *src, const ppiGui::OnResize &ev);
	//--------------------------------------------------------------------------------------------------------
	// reiht objekt in toolbox ein.
	void addControl ( CView *view );
	//--------------------------------------------------------------------------------------------------------
	void addSpace ( CCoord x ) { lastXPos+= x; }
	//--------------------------------------------------------------------------------------------------------
	MToolBox ( CFrame *parent );
	//--------------------------------------------------------------------------------------------------------
	void valueChanged ( CDrawContext *cD, CControl *pControl );
	//--------------------------------------------------------------------------------------------------------
	virtual void draw ( CDrawContext *cD );
	//--------------------------------------------------------------------------------------------------------
	~MToolBox ();
	//--------------------------------------------------------------------------------------------------------
private:

};
} // namespace ppiGui
