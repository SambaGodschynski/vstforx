namespace ppiGui{
class GObject;
//============================================================================================================
//	Klasse MouseAction:
//============================================================================================================
class MouseAction {
protected:
public:
	//--------------------------------------------------------------------------------------------------------
	MouseAction();
	//--------------------------------------------------------------------------------------------------------
	virtual ~MouseAction();
	//--------------------------------------------------------------------------------------------------------
	virtual void onMouse ( const OnMouseDrag &ev ) = 0;
	//--------------------------------------------------------------------------------------------------------
	virtual void onMouse ( const OnMouseClick &ev ) = 0;

};

//============================================================================================================
//	Klasse MANull:
//  Null Aktion.
//============================================================================================================
class MANull : public MouseAction {
private:
protected:
public:
	//--------------------------------------------------------------------------------------------------------
	virtual void onMouse ( const OnMouseDrag &ev ) {}
	//--------------------------------------------------------------------------------------------------------
	virtual void onMouse ( const OnMouseClick &ev ) {}
};
//============================================================================================================
//	Klasse MAUse:
//============================================================================================================
class MAUse : public MouseAction {
private:
protected:
public:
	//--------------------------------------------------------------------------------------------------------
	virtual void onMouse ( const OnMouseDrag &ev ) { ev.src->useByMouse( ev.cD, ev.p, ev.btn ); }
	//--------------------------------------------------------------------------------------------------------
	virtual void onMouse ( const OnMouseClick &ev ){ ev.src->useByMouse( ev.cD, ev.p, ev.btn ); }
};

//============================================================================================================
//	Klasse MAMove:
//  Drag bewegt Src GObject. Nach beendeten Drag vorgang wird Command zu DRAG_FINISHED aufgerufen.
//============================================================================================================
class MAMove : public MouseAction {
private:
protected:
public:
	//--------------------------------------------------------------------------------------------------------
	virtual void onMouse ( const OnMouseDrag &ev );
	//--------------------------------------------------------------------------------------------------------
	virtual void onMouse ( const OnMouseClick &ev ) {}
};

//============================================================================================================
//	Klasse MAConnect:
//  Drag zieht eine Line solange wie Dragvorgang. Danach wird linie wieder entfernt und  
//  Command zu DRAG_FINISHED aufgerufen.
//============================================================================================================
class MAConnect : public MouseAction {
private:
	//--------------------------------------------------------------------------------------------------------
	GLine::Ptr line;
	//--------------------------------------------------------------------------------------------------------
	CircuidView *view;
protected:
public:
	//--------------------------------------------------------------------------------------------------------
	MAConnect( CircuidView *view );
	//--------------------------------------------------------------------------------------------------------
	virtual void onMouse ( const OnMouseDrag &ev );
	//--------------------------------------------------------------------------------------------------------
	virtual void onMouse ( const OnMouseClick &ev ) {}
	//--------------------------------------------------------------------------------------------------------
	virtual ~MAConnect();

};


} // namespace ppiGui

