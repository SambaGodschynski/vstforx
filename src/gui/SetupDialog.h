//============================================================================================================
// Event OnOk:
//============================================================================================================
struct OnOk : public Event {
	long tag;
	OnOk ( long tag ) : tag(tag) {}
};
class SetupCtrl;
//============================================================================================================
// Klasse SetupDialog:
//============================================================================================================
class SetupDialog : 
	public WindowView, 
	public EventSender<OnOk>
{
friend class SetupCtrl;
private:
	//--------------------------------------------------------------------------------------------------------
	com::Settings::Ptr settings;
	//--------------------------------------------------------------------------------------------------------
	enum Controls {
		tAddDir = tNum,
		tChDir,
		tRmDir,
		tOk,
		tCancel,
		tFastScan,
		tSizeRocker,
		tSizeRockerWidth,
		tSizeRockerHeight,
		tScanNow,
		tSetupNumTags,
	};
	//--------------------------------------------------------------------------------------------------------
	CControl *controls[tSetupNumTags - tNum];
	//--------------------------------------------------------------------------------------------------------
	CControl * getControl ( long tag ) { return controls[ tag - tNum ]; }
	//--------------------------------------------------------------------------------------------------------
	ListBox *listBox;
	//--------------------------------------------------------------------------------------------------------
	void initControls();
	//--------------------------------------------------------------------------------------------------------
	void addDir();
	//--------------------------------------------------------------------------------------------------------
	void chDir();
	//--------------------------------------------------------------------------------------------------------
	void rmDir();
	//--------------------------------------------------------------------------------------------------------
	void ok();
	//--------------------------------------------------------------------------------------------------------
	void cancel();
	//--------------------------------------------------------------------------------------------------------
	void scanNow();
	//--------------------------------------------------------------------------------------------------------
	void sizeRocker( float value, long tag );
	//--------------------------------------------------------------------------------------------------------
	void writeInSetup();
	//--------------------------------------------------------------------------------------------------------
	void resetSetup();
	//--------------------------------------------------------------------------------------------------------
	void readFromSetup();
protected:
public:
	//--------------------------------------------------------------------------------------------------------
	virtual void _valueChanged(CDrawContext *cD, CControl *pControl);
	//--------------------------------------------------------------------------------------------------------
	SetupDialog( CFrame *parent );
	//--------------------------------------------------------------------------------------------------------
	virtual ~SetupDialog();
};
