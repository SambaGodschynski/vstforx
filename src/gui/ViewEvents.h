#ifndef MOUSEVENTS_H
#define MOUSEVENTS_H

#include "vstgui.h"
#include "com/Events.h"
#include "com/one4All.h"


using namespace com;
using namespace events;

namespace ppiGui{
class GObject;
//============================================================================================================
// Events:
//============================================================================================================
struct MouseEvent;
struct OnMouseClick;
struct OnMouseDrag;
struct OnMouseEnter;
struct OnConnect;
struct OnOpen;
struct OnClose;
struct OnRemove; 
struct OnMouseLeave; 
//============================================================================================================
// Methode: sendMouseEvents.
// sendet OnDragEvent oder OnClickEvent.
//============================================================================================================
extern void sendMouseEvents ( CDrawContext *cD, 
							  CPoint &p, 
							  long btn, 
							  EventSender<OnMouseDrag>  *dragSender, 
							  EventSender<OnMouseClick> *clickSender, 
							  GObject *eventSrc 
							 );
//============================================================================================================
// Event Klasse MouseEvent :
//============================================================================================================
struct MouseEvent : public Event { 
	//--------------------------------------------------------------------------------------------------------
	GObject *src;
	//--------------------------------------------------------------------------------------------------------
	CDrawContext *cD;
	//--------------------------------------------------------------------------------------------------------
	CPoint &p;
	//--------------------------------------------------------------------------------------------------------
	long btn;
	//--------------------------------------------------------------------------------------------------------
	MouseEvent ( GObject *src, CDrawContext *cD, CPoint &p, long btn ) : 
		src(src), cD(cD), p(p), btn(btn) {}
};
//============================================================================================================
// Event Klasse OnMouseClick :
//============================================================================================================
struct OnMouseClick : public MouseEvent { 
	//--------------------------------------------------------------------------------------------------------
	OnMouseClick 
		( GObject *src, CDrawContext *cD, CPoint &p, long btn ) : MouseEvent(src, cD, p, btn) {}
};
//============================================================================================================
// Event Klasse OnRemove :
//============================================================================================================
struct OnMouseEnter : public MouseEvent { 
	//--------------------------------------------------------------------------------------------------------
	OnMouseEnter 
		( GObject *src, CDrawContext *cD, CPoint &p, long btn ) : MouseEvent(src, cD, p, btn) {}
};
//============================================================================================================
// Event Klasse OnMouseLeave :
//============================================================================================================
struct OnMouseLeave : public MouseEvent {
	//--------------------------------------------------------------------------------------------------------
	OnMouseLeave 
		( GObject *src, CDrawContext *cD, CPoint &p, long btn ) : MouseEvent(src, cD, p, btn) {}
};
//============================================================================================================
// Event Klasse OnMouseDrag :
//============================================================================================================
struct OnMouseDrag : public MouseEvent { 
	//--------------------------------------------------------------------------------------------------------
	enum State { DRAG_START, DRAG, DRAG_STOP };
	//--------------------------------------------------------------------------------------------------------
	CPoint dragDirection;
	//--------------------------------------------------------------------------------------------------------
	State state;
	//--------------------------------------------------------------------------------------------------------
	OnMouseDrag 
		( GObject *src, CDrawContext *cD, CPoint &p, long btn ) : MouseEvent(src, cD, p, btn) {}
};
//============================================================================================================
//	Klasse MotionMouseListener:
//============================================================================================================
struct OnMouseMove : Event {
	CPoint point;
	CDrawContext *cD;
	OnMouseMove ( CDrawContext *cD, const CPoint &point ) : point(point), cD(cD) {}
};
//============================================================================================================
//	Klasse OnIdle:
//============================================================================================================
struct OnIdle : public com::events::Event {};
//============================================================================================================
//	Klasse OnConnect:
//============================================================================================================
struct OnConnect : public com::events::Event {
	//--------------------------------------------------------------------------------------------------------
	GObject *src;
	//--------------------------------------------------------------------------------------------------------
	GObject *dst;
	//--------------------------------------------------------------------------------------------------------
	OnConnect ( GObject *src, GObject *dst ) : src(src), dst( dst ) {}
};
//============================================================================================================
//	Klasse OnOpen:
//============================================================================================================
struct OnOpen : public com::events::Event {};
//============================================================================================================
//	Klasse OnClose:
//============================================================================================================
struct OnClose : public com::events::Event {};
//============================================================================================================
// Event Klasse OnRemove :
//============================================================================================================
struct OnRemove : public com::events::Event { 
	//--------------------------------------------------------------------------------------------------------
	GObject *gObject;
	//--------------------------------------------------------------------------------------------------------
	OnRemove ( GObject *gObject ) : gObject (gObject) {}
};
//============================================================================================================
// Event Resize:
//============================================================================================================
struct OnResize : public Event {
	VSTGUI::CRect size;
	OnResize ( const VSTGUI::CRect &size ) : size(size) {}
};
} // namespace ppiGui
#endif


