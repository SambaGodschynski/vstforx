//============================================================================================================
//	Klasse Command:
//  Schnitstelle im sinne des Command Pattern.
//============================================================================================================
class Command {
private:
	//--------------------------------------------------------------------------------------------------------
	virtual void _execute () = 0; 
public:
	//--------------------------------------------------------------------------------------------------------
	typedef std::shared_ptr<Command> Ptr;
	//--------------------------------------------------------------------------------------------------------
	typedef list<Ptr> Container;
	//--------------------------------------------------------------------------------------------------------
	Command() {}
	//--------------------------------------------------------------------------------------------------------
	virtual ~Command(){}
	//--------------------------------------------------------------------------------------------------------
	virtual Ptr createReverseCommand ();
	//--------------------------------------------------------------------------------------------------------
	void execute (){
		_execute();
	}
};
//============================================================================================================
//	Klasse CmdNull:
//  Tut Null.
//============================================================================================================
class CmdNull : public Command {
private:
	//--------------------------------------------------------------------------------------------------------
	virtual void _execute ( ) {} 
};

//============================================================================================================
//	Klasse CommandExecuter:
//============================================================================================================
class CommandExecuter {
public:
	//--------------------------------------------------------------------------------------------------------
	typedef std::shared_ptr<CommandExecuter> Ptr;
private:
	//--------------------------------------------------------------------------------------------------------
	Command::Container commands;
protected:
	//--------------------------------------------------------------------------------------------------------
	Mutex mutex;
public:
	//--------------------------------------------------------------------------------------------------------
	enum Priority { NORMAL, HIGH };
	//--------------------------------------------------------------------------------------------------------
	size_t getNumCommands() const { return commands.size(); }
	//--------------------------------------------------------------------------------------------------------
	bool hasNoCommands() const { return commands.empty(); }
	//--------------------------------------------------------------------------------------------------------
	virtual void addCommand ( Command::Ptr cmd, Priority priority = NORMAL ) { 
		TRY_TO_LOCK_TIMED ( CommandExecuter::mutex );
		if ( priority == NORMAL ) commands.push_back ( cmd ); 
		else commands.push_front (cmd);
	}
	//--------------------------------------------------------------------------------------------------------
	// nebenlaeufig ausfuehrbar
	virtual void executeCommands ();
};
