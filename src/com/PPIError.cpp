namespace com{
namespace ppiError{
//============================================================================================================
// Klasse: PPIError.
//============================================================================================================
//------------------------------------------------------------------------------------------------------------
PPIError::PPIError (string err, string source, long line ){
	error = err;
	src = source;
	linenumber = line;
	TOLOG ( toString() ); 
}
//------------------------------------------------------------------------------------------------------------
string PPIError::src2String() const {
	return "source:" + src + " line:" + MyString((int)linenumber);
}
//------------------------------------------------------------------------------------------------------------
void PPIError::showMessage() {
	com::osMessageBox ( "Error!", error, MSG_ALERT ); 
};
//------------------------------------------------------------------------------------------------------------
const char* PPIError::what() const throw() {
    tmp = toString();
    return tmp.c_str();
}
} //namespace ppiError
} //namespace com
